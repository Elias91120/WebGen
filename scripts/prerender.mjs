// Prerenders each page into its built HTML (dist/<page>/index.html), after `vite build` and the
// SSR build of src/prerender.tsx (dist-ssr/). Pages are rendered in French; the browser then
// hydrates them and switches to the visitor's language if needed. Then writes dist/sitemap.xml:
// the main pages below plus every content page of src/content/pages.ts.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { render, renderContent, contentPages } = await import(pathToFileURL(join(root, 'dist-ssr', 'prerender.js')).href);

const ENTRIES = {
  'index.html': 'home',
  'offres/index.html': 'offers',
  'realisations/index.html': 'work',
  'equipe/index.html': 'team',
  '17-octobre/index.html': 'game',
  'ia/index.html': 'ia',
};

// The empty root of each page, with its attributes (content pages carry data-page).
const EMPTY_ROOT = /<div id="root"([^>]*)><\/div>/;

function prerender(file, body) {
  const path = join(root, 'dist', file);
  const html = readFileSync(path, 'utf8');
  if (!EMPTY_ROOT.test(html)) throw new Error(`${file}: empty <div id="root"> not found`);
  writeFileSync(path, html.replace(EMPTY_ROOT, (_, attrs) => `<div id="root"${attrs} data-prerendered="true">${body}</div>`));
  console.log(`prerendered ${file} (${Math.round(body.length / 1024)} KB)`);
}

for (const [file, page] of Object.entries(ENTRIES)) prerender(file, render(page));
for (const { path } of contentPages) prerender(`${path.slice(1)}/index.html`, renderContent(path));

// Sitemap: one address per page, the same as its canonical (no www, no trailing slash).
const SITE = 'https://3geeks.fr';
const MAIN_PAGES = [
  { path: '', priority: '1.0', changefreq: 'weekly' },
  { path: '/offres', priority: '0.9', changefreq: 'monthly' },
  { path: '/realisations', priority: '0.9', changefreq: 'weekly' },
  { path: '/ia', priority: '0.9', changefreq: 'monthly' },
  { path: '/equipe', priority: '0.7', changefreq: 'monthly' },
  { path: '/17-octobre', priority: '0.8', changefreq: 'weekly' },
];
const today = new Date().toISOString().slice(0, 10);
const urls = [
  ...MAIN_PAGES.map((p) => ({ ...p, lastmod: today })),
  ...contentPages.map((p) => ({ path: p.path, priority: '0.8', changefreq: 'monthly', lastmod: p.updated })),
];
const sitemap = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<!-- Generated by scripts/prerender.mjs at build time: main pages + src/content/pages.ts. -->',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...urls.map((u) => `  <url><loc>${SITE}${u.path}</loc><lastmod>${u.lastmod}</lastmod><changefreq>${u.changefreq}</changefreq><priority>${u.priority}</priority></url>`),
  '</urlset>',
  '',
].join('\n');
writeFileSync(join(root, 'dist', 'sitemap.xml'), sitemap);
console.log(`sitemap.xml (${urls.length} pages)`);
